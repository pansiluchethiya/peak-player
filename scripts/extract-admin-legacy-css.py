"""Extract the legacy admin rules that the Next.js admin app still references
but never defined, and emit admin/app/legacy.css.

Only rules whose selector mentions one of the audited missing class names are
kept, plus @keyframes they depend on. Legacy token variables are imported
separately from public/admin/tokens.css.
"""
import glob
import os
import re

ROOT = "/home/pansilu/.local/share/opencode/worktree/950f13/peak-player-embed-platform"
ADMIN_TSX = (glob.glob(f"{ROOT}/admin/app/**/*.tsx", recursive=True)
             + glob.glob(f"{ROOT}/admin/components/**/*.tsx", recursive=True))

used = set()
for f in ADMIN_TSX:
    src = open(f).read()
    for m in re.finditer(r'className=(?:"([^"]*)"|\{`([^`]*)`\})', src):
        raw = m.group(1) or m.group(2) or ""
        for c in re.split(r"\s+", raw):
            c = c.strip()
            if c and "$" not in c and "{" not in c:
                used.add(c)

app_css = ""
for f in glob.glob(f"{ROOT}/admin/app/*.css") + glob.glob(f"{ROOT}/ui/*.css"):
    if f.endswith("/legacy.css"):
        continue  # generated output — never treat it as a source of truth
    app_css += open(f).read()
defined = set(re.findall(r"\.([a-zA-Z][a-zA-Z0-9_-]*)", app_css))
missing = used - defined

FILES = ["base.css", "base-2.css", "components.css", "components-2.css",
         "components-3.css", "components-4.css", "forms.css", "tables.css",
         "charts.css", "layout.css", "layout-2.css", "layout-3.css",
         "layout-4.css", "layout-5.css", "layout-6.css", "layout-7.css",
         "layout-8.css"]


def strip_comments(text):
    return re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def parse_blocks(text, start=0, end=None):
    """Yield (selector, body, is_at_rule) for top-level blocks."""
    end = len(text) if end is None else end
    i = start
    buf = []
    while i < end:
        ch = text[i]
        if ch == "{":
            selector = "".join(buf).strip()
            buf = []
            depth = 1
            j = i + 1
            while j < end and depth:
                if text[j] == "{":
                    depth += 1
                elif text[j] == "}":
                    depth -= 1
                j += 1
            body = text[i + 1:j - 1]
            yield selector, body
            i = j
            continue
        if ch == "}":
            buf = []
            i += 1
            continue
        buf.append(ch)
        i += 1


def class_hits(selector):
    names = re.findall(r"\.([a-zA-Z][a-zA-Z0-9_-]*)", selector)
    return [n for n in names if n in missing]


kept = []          # rendered CSS blocks
keyframes = {}     # name -> full block text


def render(selector, body):
    """Return a list of CSS text blocks to keep, preserving @media nesting."""
    sel = " ".join(selector.split())
    if sel.startswith("@media") or sel.startswith("@supports") or sel.startswith("@layer"):
        inner = []
        for s2, b2 in parse_blocks(body):
            inner.extend(render(s2, b2))
        if not inner:
            return []
        return [f"{sel} {{\n" + "\n".join(inner) + "\n}"]
    if sel.startswith("@keyframes") or sel.startswith("@-webkit-keyframes"):
        name = sel.split()[-1]
        keyframes[name] = f"{sel} {{{body}}}"
        return []
    if sel.startswith("@"):
        return []
    if class_hits(sel):
        return [f"{sel} {{\n{body.strip()}\n}}"]
    return []


for name in FILES:
    path = f"{ROOT}/public/admin/{name}"
    if not os.path.exists(path):
        continue
    text = strip_comments(open(path).read())
    for sel, body in parse_blocks(text):
        kept.extend(render(sel, body))

# dedupe identical blocks, preserving first-seen order
seen = set()
order = []
for block in kept:
    if block in seen:
        continue
    seen.add(block)
    order.append(block)

all_css = "\n".join(order)
used_kf = [n for n in keyframes if re.search(rf"animation[^;]*\b{re.escape(n)}\b", all_css)]

out = ["""/* admin/app/legacy.css
 * GENERATED by scripts/extract-admin-legacy-css.py — do not edit by hand.
 *
 * The Next.js admin pages were ported from the legacy static control plane and
 * kept its class names (.btn, .field, .auth-*, .page-head, ...). Only the
 * .admin-* chrome was ported to admin.css, so everything else rendered
 * unstyled. This file carries over exactly the legacy rules for class names the
 * app still references but that no app stylesheet defines.
 *
 * Token variables come from public/admin/tokens.css, imported just before this
 * file in globals.css.
 */
"""]
for name in used_kf:
    out.append(keyframes[name])
    out.append("")
out.extend(order)

dest = f"{ROOT}/admin/app/legacy.css"
open(dest, "w").write("\n".join(out))
print(f"missing classes: {len(missing)}")
print(f"rules kept: {len(order)} blocks, {len(seen)} unique")
print(f"keyframes: {used_kf}")
print(f"wrote {dest} ({os.path.getsize(dest)} bytes)")
